#!/bin/bash
# ==============================================================================
# 🤸 リハビリテーション科 指示受け・実施モニター 単体起動スクリプト (Port 8085)
# ==============================================================================

DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$DIR" || exit 1

# ポート 8085 を占有しているプロセスを解放
fuser -k 8085/tcp 2>/dev/null
sleep 1

export PORT=8085
echo "🚀 リハビリテーション科 指示受けサーバー (Port 8085) を起動します..."
echo "🌐 URL: http://localhost:8085/"
echo "💡 終了するには [ Ctrl + C ] を押してください。"
echo "--------------------------------------------------------"

node server.js
