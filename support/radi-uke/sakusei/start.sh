#!/bin/bash
# ==============================================================================
# 🩻 放射線科 指示受け・実施モニター 単体起動スクリプト (Port 8081)
# ==============================================================================

DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$DIR" || exit 1

# ポート 8081 を占有しているプロセスを解放
fuser -k 8081/tcp 2>/dev/null
sleep 1

export PORT=8081
echo "🚀 放射線科 指示受けサーバー (Port 8081) を起動します..."
echo "🌐 URL: http://localhost:8081/"
echo "💡 終了するには [ Ctrl + C ] を押してください。"
echo "--------------------------------------------------------"

node server.js
